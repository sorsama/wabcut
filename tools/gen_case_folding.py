"""Writes src/model/src/CaseFolding.inc: Unicode simple case folding for Find and Replace (TextFind.h).

Simple folding maps one code point to one (CaseFolding.txt statuses C and S): Python's str.casefold() when it gives a
single code point, else str.lower() when that does. The table is compressed into runs {first, count, delta, step}:
first + k * step (k < count) folds to itself + delta. Run it again when Python's Unicode version moves on:

    python -I tools/gen_case_folding.py
"""

import pathlib
import sys
import unicodedata


def pairs():
    out = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        f = c.casefold()
        if len(f) != 1:
            f = c.lower()
            if len(f) != 1:
                continue
        if f != c:
            out.append((cp, ord(f)))
    return out


def runs(table):
    out = []
    i = 0
    while i < len(table):
        first, to = table[i]
        delta = to - first
        count = 1
        step = 1
        if i + 1 < len(table):
            next_step = table[i + 1][0] - first
            if next_step in (1, 2) and table[i + 1][1] - table[i + 1][0] == delta:
                step = next_step
                j = i + 1
                while j < len(table) and table[j][0] - table[j - 1][0] == step and table[j][1] - table[j][0] == delta:
                    j += 1
                count = j - i
        out.append((first, count, delta, step if count > 1 else 1))
        i += count
    return out


def main():
    lines = [
        '// Generated by tools/gen_case_folding.py (Unicode %s simple case folding). Do not edit.' % unicodedata.unidata_version,
        '// {first code point, count, delta, step}: first + k * step (k < count) folds to itself + delta.',
        'constexpr FoldRun kFoldRuns[] = {',
    ]
    line = '   '
    for r in runs(pairs()):
        item = ' {0x%X, %d, %d, %d},' % r
        if len(line) + len(item) > 118:
            lines.append(line)
            line = '   '
        line += item
    lines.append(line)
    lines.append('};')
    target = pathlib.Path(__file__).resolve().parent.parent / 'src' / 'model' / 'src' / 'CaseFolding.inc'
    target.write_bytes(('\n'.join(lines) + '\n').encode('utf-8'))
    sys.stdout.write('wrote %s\n' % target)


if __name__ == '__main__':
    main()
