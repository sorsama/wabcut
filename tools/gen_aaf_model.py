#!/usr/bin/env python3
"""Generates src/interchange/src/AafModel.cpp: the AAF baseline object model (class, property and type definitions)
that Wabcut's AAF writer stores in every file's MetaDictionary and checks its objects against.

The definitions are the AAF Object Specification's identifiers as pyaaf2 (MIT, https://github.com/markreidvfx/pyaaf2)
tabulates them in aaf2/model (its baseline model, without the Avid extensions). Run with pyaaf2 importable:

    python tools/gen_aaf_model.py > src/interchange/src/AafModel.cpp

The output is deterministic (pyaaf2's dictionary order); dynamic property ids (local tags >= 0x8000) are numbered as
pyaaf2 numbers them, downwards from 0xFFFF in class order.
"""

import sys

import aaf2
from aaf2.model import classdefs as model_classes
from aaf2.model import typedefs as model_types


def auid_parts(text):
    h = text.replace('-', '').lower()
    if len(h) != 32:
        raise ValueError(text)
    d1 = int(h[0:8], 16)
    d2 = int(h[8:12], 16)
    d3 = int(h[12:16], 16)
    d4 = [int(h[16 + 2 * i:18 + 2 * i], 16) for i in range(8)]
    return d1, d2, d3, d4


def auid_cpp(text):
    d1, d2, d3, d4 = auid_parts(text)
    return 'A(0x%08x, 0x%04x, 0x%04x, {%s})' % (d1, d2, d3, ', '.join('0x%02x' % b for b in d4))


def is_auid(text):
    return isinstance(text, str) and len(text.replace('-', '')) == 32 and text.count('-') == 4


ROOT_TYPES = {
    'HeaderStrongRefence': ('05022800-0000-0000-060E-2B3401040101', '0d010101-0101-2f00-060e-2b3402060101'),
    'MetaDictionaryStrongReference': ('05022700-0000-0000-060E-2B3401040101', '0d010101-0225-0000-060e-2b3402060101'),
}

CATEGORIES = ['ints', 'enums', 'records', 'fixed_arrays', 'var_arrays', 'renames', 'strings', 'streams', 'opaques',
              'extenums', 'chars', 'generic_chars', 'indirects', 'sets', 'strongrefs', 'weakrefs']

KIND = {
    'ints': 'Integer', 'enums': 'Enum', 'records': 'Record', 'fixed_arrays': 'FixedArray',
    'var_arrays': 'VarArray', 'renames': 'Rename', 'strings': 'String', 'streams': 'Stream', 'opaques': 'Opaque',
    'extenums': 'ExtEnum', 'chars': 'Character', 'generic_chars': 'GenericCharacter', 'indirects': 'Indirect',
    'sets': 'Set', 'strongrefs': 'StrongRef', 'weakrefs': 'WeakRef',
}


def main():
    out = []
    w = out.append

    # --- types, in pyaaf2's registration order: the root strong references, then each category -----------------
    types = []  # (category, name, args)
    for name, args in ROOT_TYPES.items():
        types.append(('strongrefs', name, args))
    for cat in CATEGORIES:
        for name, args in getattr(model_types, cat).items():
            types.append((cat, name, args))

    type_index = {}
    for i, (cat, name, args) in enumerate(types):
        auid = args if isinstance(args, str) else args[0]
        type_index[auid.lower()] = i
        type_index[name] = i

    def type_ref(ref):
        key = ref.lower() if is_auid(ref) else ref
        if key not in type_index:
            raise KeyError('unknown type %r' % ref)
        return type_index[key]

    # --- classes: the root class first (not stored in the MetaDictionary), then the model's -----------------------
    classes = [('Root', ('b3b398a5-1c90-11d4-8053-080036210804', None, True, {
        'MetaDictionary': ('0d010301-0101-0100-060e-2b3401010102', 0x0001, '05022700-0000-0000-060E-2B3401040101',
                           False, False),
        'Header': ('0d010301-0102-0100-060e-2b3401010102', 0x0002, '05022800-0000-0000-060E-2B3401040101',
                   False, False),
    }))]
    for name, args in model_classes.classdefs.items():
        classes.append((name, args))
    class_index = {}
    for i, (name, args) in enumerate(classes):
        class_index[args[0].lower()] = i
        class_index[name] = i
    for alias, name in model_classes.aliases.items():
        class_index.setdefault(alias, class_index[name])

    def class_ref(ref):
        key = ref.lower() if is_auid(ref) else ref
        return class_index[key]

    next_pid = [0xFFFF]

    def dynamic_pid():
        pid = next_pid[0]
        next_pid[0] -= 1
        return pid

    try:
        from importlib.metadata import version
        pyaaf2_version = version('pyaaf2')
    except Exception:  # noqa: BLE001 - the version is informational only
        pyaaf2_version = 'unknown'
    w('// Generated by tools/gen_aaf_model.py from pyaaf2 %s (aaf2/model, MIT licence: THIRD-PARTY-NOTICES.md): the AAF'
      % pyaaf2_version)
    w('// baseline object model, every class, property and type definition of the AAF Object Specification. Do not')
    w('// edit; regenerate.')
    w('')
    w('// clang-format off')
    w('')
    w('#include "AafModel.h"')
    w('')
    w('namespace wabcut::interchange::detail::aaf {')
    w('')
    w('namespace {')
    w('')
    w('constexpr Auid A(std::uint32_t d1, std::uint16_t d2, std::uint16_t d3, std::array<std::uint8_t, 8> d4) {')
    w('    return Auid{d1, d2, d3, d4};')
    w('}')
    w('')

    # Per-type side tables.
    for i, (cat, name, args) in enumerate(types):
        if cat == 'enums':
            elements = args[2]
            w('constexpr EnumElement kEnum%d[] = {%s};' % (i, ', '.join(
                '{"%s", %d}' % (n, v) for v, n in elements.items())))
        elif cat == 'records':
            w('constexpr RecordMember kRecord%d[] = {%s};' % (i, ', '.join(
                '{"%s", %d}' % (n, type_ref(t)) for n, t in args[1])))
        elif cat == 'extenums':
            w('constexpr ExtEnumElement kExtEnum%d[] = {' % i)
            for v, n in args[1].items():
                w('    {"%s", %s},' % (n, auid_cpp(v)))
            w('};')
        elif cat == 'weakrefs':
            w('constexpr Auid kPath%d[] = {%s};' % (i, ', '.join(auid_cpp(a) for a in args[2])))
    w('')

    w('constexpr TypeDef kTypeTable[] = {')
    for i, (cat, name, args) in enumerate(types):
        kind = KIND[cat]
        auid = args if isinstance(args, str) else args[0]
        fields = ['"%s"' % name, auid_cpp(auid), 'TypeKind::%s' % kind]
        size, signed, element, count, ref_class = 0, 'false', -1, 0, -1
        extra = []
        if cat == 'ints':
            size, signed = args[1], 'true' if args[2] else 'false'
        elif cat == 'enums':
            element = type_ref(args[1])
            extra.append('.enumElements = kEnum%d' % i)
        elif cat == 'records':
            extra.append('.members = kRecord%d' % i)
        elif cat == 'fixed_arrays':
            element, count = type_ref(args[1]), args[2]
        elif cat in ('var_arrays', 'sets', 'renames', 'strings'):
            element = type_ref(args[1])
        elif cat == 'extenums':
            extra.append('.extEnumElements = kExtEnum%d' % i)
        elif cat == 'generic_chars':
            size = args[1]
        elif cat == 'strongrefs':
            ref_class = class_ref(args[1])
        elif cat == 'weakrefs':
            ref_class = class_ref(args[1])
            extra.append('.targetPath = kPath%d' % i)
        fields += ['.size = %d' % size, '.isSigned = %s' % signed, '.element = %d' % element, '.count = %d' % count,
                   '.refClass = %d' % ref_class] + extra
        # Designated initializers need the leading members named too.
        fields[0] = '.name = ' + fields[0]
        fields[1] = '.id = ' + fields[1]
        fields[2] = '.kind = ' + fields[2]
        w('    {%s}, // %d' % (', '.join(fields), i))
    w('};')
    w('')

    prop_rows = []
    class_rows = []
    for ci, (name, args) in enumerate(classes):
        auid, parent, concrete, props = args
        first = len(prop_rows)
        for pname, pargs in props.items():
            pid = pargs[1]
            if pid is None:
                pid = dynamic_pid()
            prop_rows.append('    {.name = "%s", .id = %s, .pid = 0x%04x, .type = %d, .optional = %s, .unique = %s},'
                             % (pname, auid_cpp(pargs[0]), pid, type_ref(pargs[2]),
                                'true' if pargs[3] else 'false', 'true' if pargs[4] else 'false'))
        parent_index = class_ref(parent) if parent else -1
        class_rows.append('    {.name = "%s", .id = %s, .parent = %d, .concrete = %s, .firstProperty = %d, '
                          '.propertyCount = %d}, // %d'
                          % (name, auid_cpp(auid), parent_index, 'true' if concrete else 'false', first,
                             len(prop_rows) - first, ci))

    w('constexpr PropertyDef kPropertyTable[] = {')
    out.extend(prop_rows)
    w('};')
    w('')
    w('constexpr ClassDef kClassTable[] = {')
    out.extend(class_rows)
    w('};')
    w('')
    w('} // namespace')
    w('')
    w('std::span<const TypeDef> types() { return kTypeTable; }')
    w('std::span<const PropertyDef> properties() { return kPropertyTable; }')
    w('std::span<const ClassDef> classes() { return kClassTable; }')
    w('')
    w('} // namespace wabcut::interchange::detail::aaf')
    w('')
    w('// clang-format on')
    sys.stdout.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
