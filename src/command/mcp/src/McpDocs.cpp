std::string mcpMarkdown(const CommandRegistry& registry) {
    EditSession session;
    McpServerOptions options;
    options.allowed = CapabilitySet::of({Capability::Read, Capability::EditSequence, Capability::EditProject});
    options.projectPath = "project.wabcut";
    const McpServer server(session, options, registry);
    const Json tools = server.tools();
    // What --allow-analysis and --allow-files add (listed apart below).
    McpServerOptions everything = options;
    everything.allowed.bits |= CapabilitySet::of({Capability::MediaAnalysis}).bits;
    everything.fileRoots = {"."};
    const McpServer wider(session, everything, registry);
    const Json widerTools = wider.tools();

    std::string legacy;
    for (const std::string_view v : legacyProtocolVersions()) {
        legacy += (legacy.empty() ? "" : " and ") + std::string("**") + std::string(v) + "**";
    }

    std::string md;
    md += "# MCP server\n\n";
    md += "<!-- Generated by wabcut_command_docgen (src/command/mcp/src/McpDocs.cpp); do not edit by hand.\n"
          "     Regenerate: build\\win-msvc\\bin\\wabcut_command_docgen.exe docs/commands.md docs/mcp.md -->\n\n";
    md += "`wabcut-cli mcp` serves one project to external AI agents (Claude Desktop, Claude Code, Codex, Cursor, and "
          "others) over the [Model Context Protocol](https://modelcontextprotocol.io). The tools are the typed edit "
          "commands of [docs/commands.md](commands.md): every edit is validated, previewable with `dryRun`, and one "
          "undo step. The server is local only: stdio, no network, no files besides the project.\n\n";

    md += "## Protocol\n\n";
    md += "* **Implemented revision: MCP " + std::string(kProtocolVersion) +
          "** (stateless: every request carries `_meta` `io.modelcontextprotocol/protocolVersion` and "
          "`clientCapabilities`; `server/discover`; results carry `resultType`). Checked against "
          "<https://modelcontextprotocol.io/specification/" + std::string(kProtocolVersion) + "> on 2026-10-11.\n";
    md += "* Clients that open with `initialize` get the handshake-based revisions " + legacy +
          " (the spec's dual-era server, \"Versioning: Backward Compatibility\"). The server answers with the "
          "requested revision when it serves it, otherwise with the newest one it serves; the client then decides "
          "whether to continue.\n";
    md += "* Transport: stdio, one JSON-RPC 2.0 message per line, UTF-8. stdout carries only protocol messages; "
          "diagnostics go to stderr. JSON-RPC batches are not supported (removed from MCP in 2025-06-18).\n\n";
    md += "| Method | Notes |\n|---|---|\n";
    md += "| `server/discover` | Supported versions, capabilities (`tools`, `resources`), server info, instructions. |\n";
    md += "| `initialize`, `notifications/initialized` | Legacy handshake (see above). |\n";
    md += "| `ping` | Always answered. |\n";
    md += "| `tools/list`, `tools/call` | The tools below; results carry `structuredContent` (matching each tool's "
          "`outputSchema`) and the same JSON as text. |\n";
    md += "| `resources/list`, `resources/templates/list`, `resources/read` | `wabcut://project/summary` and "
          "`wabcut://sequence/{id}`. |\n";
    md += "| `notifications/cancelled` | Stops the running call at its next checkpoint (nothing is committed) or "
          "skips a queued request; no response is sent for it. |\n";
    md += "| `notifications/progress` | Sent for calls with `_meta.progressToken`: once per batch step, per range of "
          "`timeline_removeSilences` and before a commit. `progress` counts up; there is no `total`. |\n\n";
    md += "**Errors.** Protocol problems are JSON-RPC errors:\n\n";
    md += "| Code | When |\n|---|---|\n";
    md += "| -32700 | The line is not JSON. |\n";
    md += "| -32600 | Not a JSON-RPC 2.0 request (bad `jsonrpc`, `id` or `method`), a batch array, a message over 4 MiB "
          "or nested deeper than 64. |\n";
    md += "| -32601 | Unknown method. |\n";
    md += "| -32602 | Bad params: missing `_meta` fields (2026-07-28) without a prior `initialize`, unknown tool, "
          "arguments not an object, unknown resource. |\n";
    md += "| -32022 | `_meta` names a protocol version the server does not serve; `data.supported` lists the one it "
          "does. |\n";
    md += "| -32603 | Internal error. |\n\n";
    md += "Problems with a tool call itself (bad parameters, a stale revision, an edit the model refuses, a "
          "read-only server) come back as a normal result with `isError: true`. The text explains the problem, and "
          "`structuredContent.error` has `code`, `message` and `details`, so the model can correct itself.\n\n";

    md += "## Setup\n\n";
    md += "Run the server with `wabcut-cli mcp --project <file.wabcut>`:\n\n";
    md += "| Flag | Effect |\n|---|---|\n";
    md += "| `--project <file>` | The project to serve (required). |\n";
    md += "| `--allow-edit` | Enables the edit tools (`EditSequence`, `EditProject`), undo/redo and `project_save`. "
          "Without it the server is read-only. |\n";
    md += "| `--allow-analysis` | Also serves the analysis commands (`MediaAnalysis`: `transcript.transcribe` with local "
          "transcription and the analysis cache, `audio.loudness`). They decode media and can run long: raise "
          "`--timeout-ms`. Network commands are never served. |\n";
    md += "| `--allow-files` | Also serves the commands that read or write files (review packages, CDL and LUT files, "
          "`project.merge`, `lottie.import`, ...), confined to the project's folder: every path they are given must "
          "lie inside it once symlinks and junctions are resolved. Without it they are not listed and refused by "
          "name. `plugins.scan` (native code) is never served. |\n";
    md += "| `--files-folder <dir>` | One more folder those commands may use (repeatable; implies `--allow-files`). |\n";
    md += "| `--save-on-exit` | Saves the project when the client disconnects, if anything changed (needs "
          "`--allow-edit`). |\n";
    md += "| `--autosave` | Saves after every change (needs `--allow-edit`). |\n";
    md += "| `--timeout-ms <n>` | Longest a tool call may run (default 30000). |\n\n";
    md += "Without a save flag, changes stay in memory until the agent calls `project_save`. Every save is atomic and "
          "keeps rotated `.bak` copies.\n\n";
    md += "### Claude Desktop\n\n";
    md += "Add to `claude_desktop_config.json` (Windows: `%APPDATA%\\Claude\\`, macOS: `~/Library/Application "
          "Support/Claude/`), then restart Claude Desktop:\n\n";
    md += "```json\n"
          "{\n"
          "  \"mcpServers\": {\n"
          "    \"wabcut\": {\n"
          "      \"command\": \"C:\\\\Program Files\\\\Wabcut\\\\wabcut-cli.exe\",\n"
          "      \"args\": [\"mcp\", \"--project\", \"C:\\\\Users\\\\me\\\\Videos\\\\Rough cut.wabcut\", "
          "\"--allow-edit\", \"--save-on-exit\"]\n"
          "    }\n"
          "  }\n"
          "}\n"
          "```\n\n";
    md += "Leave out `--allow-edit` (and the save flag) for a read-only connection.\n\n";
    md += "### Claude Code\n\n";
    md += "```\n"
          "claude mcp add wabcut -- wabcut-cli mcp --project ./rough-cut.wabcut --allow-edit\n"
          "```\n\n";
    md += "or check a project-scoped `.mcp.json` into the repository:\n\n";
    md += "```json\n"
          "{\n"
          "  \"mcpServers\": {\n"
          "    \"wabcut\": {\n"
          "      \"command\": \"wabcut-cli\",\n"
          "      \"args\": [\"mcp\", \"--project\", \"rough-cut.wabcut\", \"--allow-edit\"]\n"
          "    }\n"
          "  }\n"
          "}\n"
          "```\n\n";
    md += "### Codex\n\n";
    md += "```\n"
          "codex mcp add wabcut -- wabcut-cli mcp --project /home/me/rough-cut.wabcut --allow-edit\n"
          "```\n\n";
    md += "or in `~/.codex/config.toml`:\n\n";
    md += "```toml\n"
          "[mcp_servers.wabcut]\n"
          "command = \"wabcut-cli\"\n"
          "args = [\"mcp\", \"--project\", \"/home/me/rough-cut.wabcut\", \"--allow-edit\"]\n"
          "```\n\n";
    md += "Cursor and other clients use the same `mcpServers` JSON as Claude Desktop.\n\n";

    md += "## Safety model\n\n";
    md += "* **Read-only by default.** The client gets the `Read` capability. `--allow-edit` adds `EditSequence` and "
          "`EditProject`, `--allow-analysis` adds `MediaAnalysis`; `Network` commands are never served. Edit tools "
          "are not even listed on a read-only server; calling one anyway returns an `isError` result "
          "(`PermissionDenied`) that tells the user to restart with `--allow-edit`.\n";
    md += "* **AI models.** Read tools that run a local model (`search.footage`, `shorts.find`, `takes.find`) are "
          "served read-only: they read the project and its media and never change them. The analysis commands that "
          "run models need `--allow-analysis`; edit tools that run one (reframe, shorts, dub, ...) need "
          "`--allow-edit`, and the paid ones only estimate here.\n";
    md += "* **Validated, previewable, undoable.** Edits go through the command engine: params are checked against "
          "the schema, references resolve, and results pass the model invariants and the locked-track guard. "
          "`dryRun: true` previews without committing. Every commit (and every `edit_batch`) is one undo step, and "
          "`edit_undo` / `edit_redo` work like the menu items.\n";
    md += "* **Revisions.** Every result reports the session `revision`. A commit with a stale `expectedRevision` "
          "fails with `StaleRevision` instead of editing. Without one, the commit is based on the current revision "
          "and the result says `assumedRevision: true`. `idempotencyKey` makes retries safe.\n";
    md += "* **Bounded input.** Messages are limited to 4 MiB and 64 levels of nesting, `edit_batch` to 1000 "
          "commands, and every argument is checked against its schema.\n";
    md += "* **Call timeout.** It is checked at the engine's checkpoints (between batch steps, inside long commands, "
          "before a commit). A call that runs past it stops with `TimedOut` and commits nothing. Work between two "
          "checkpoints (one model edit) always finishes.\n";
    md += "* **Files.** An MCP client is a model steered by what it reads (project content included), so it never "
          "picks files: the commands that read or write the files their parameters name are not listed and are "
          "refused by name (`PermissionDenied`, `details.touchesFiles`). With `--allow-files` they are served, but "
          "every path must be absolute and lie inside the project's folder or a `--files-folder` once symlinks and "
          "junctions are resolved (`details.confined` when it does not). `plugins.scan` is never served. The project "
          "file itself: `project_save` writes it, or a copy next to it (`copyName` is a plain file name ending in "
          "`.wabcut`: no folders, no `..`, no device names). There is no shell or network access.\n";
    md += "* **Annotations are hints.** Read tools are `readOnlyHint: true`; edit tools are `destructiveHint: "
          "true` (they change the project, although undo restores it); `openWorldHint` is always false.\n\n";

    md += "## Edit results\n\n";
    md += "Edit tools return `{ok, revision, basedOnRevision, dryRun, committed, changes, layout, ...}`:\n\n";
    md += "* `changes`: per sequence, the touched tracks (`\"V1\"`) with `[start, end)` timecode ranges, plus the "
          "added, removed and modified clip ids and what changed on them (`roles`).\n";
    md += "* `layout`: the resulting clips of those tracks in the compact `sequence.summary` format (`clipFields` "
          "plus arrays). For a dry run this is the preview, so an agent can check the result before committing.\n";
    md += "* `createdIds`, `warnings`, `steps` (`edit_batch`), `undone` / `redone`, `canUndo` / `canRedo`, `saved` "
          "(autosave), `replayed` (idempotency) when they apply.\n\n";

    md += "## Resources\n\n";
    md += "| URI | Content |\n|---|---|\n";
    md += "| `wabcut://project/summary` | The `project.summary` JSON plus `revision`. |\n";
    md += "| `wabcut://sequence/{id}` | The `sequence.summary` JSON of that sequence plus `revision` (listed per "
          "sequence; also a resource template). |\n\n";

    md += "## Tools\n\n";
    md += "Tool names use `_` for the command's `.` (`timeline_rippleDelete` is `timeline.rippleDelete`). Parameters "
          "are documented in [docs/commands.md](commands.md); edit tools also take `dryRun`, `expectedRevision` and "
          "`idempotencyKey`.\n\n";
    md += "| Tool | Title | Access | Description |\n|---|---|---|---|\n";
    std::set<std::string> basic;
    for (const Json& tool : tools) {
        basic.insert(tool["name"].get<std::string>());
    }
    for (const Json& tool : widerTools) {
        const std::string name = tool["name"].get<std::string>();
        const CommandSpec* spec = registry.find(name);
        const bool read = tool["annotations"]["readOnlyHint"].get<bool>();
        std::string access = read ? "read" : "edit (`--allow-edit`)";
        if (!basic.contains(name) && spec && spec->touchesFiles) {
            access = (read ? std::string("read") : std::string("edit")) + ", files (`--allow-files`, confined)";
        } else if (!basic.contains(name)) {
            access = "analysis (`--allow-analysis`)";
        }
        md += "| `" + name + "` | " + cell(tool["title"].get<std::string>()) + " | " + access + " | " +
              cell(tool["description"].get<std::string>()) + " |\n";
    }
    md += "\n";
    return md;
}

